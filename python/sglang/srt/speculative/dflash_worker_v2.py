# CC conditional decode (cc_conditional_decode.py): captures several decode
# ticks per host round-trip inside a CUDA-graph WHILE loop. Any host sync
# (.item()/.sum() on a freshly-built tensor) inside the captured region
# either fails capture outright or silently breaks replay-time reuse, so
# under this flag the decode/verify path must use the pre-computed
# nxt_kv_lens_cpu/_sum upper bound unconditionally instead of the
# per-tick .sum() bookkeeping. Strictly opt-in; defaults OFF, in which case
# behavior is byte-for-byte identical to before. Read once at import.
SGLANG_CC_CONDITIONAL_DECODE = get_bool_env_var("SGLANG_CC_CONDITIONAL_DECODE")

# Oracle mode: how confident the draft model must be (log P(oracle_token))
# for an oracle-mode row's block position to count toward this tick's commit
# length. Oracle tokens are usually generated by a different model than the
# one being served, so this is deliberately a soft plausibility bar, not
# argmax equality -- see oracle_decode/forced_token_pool.py's module
# docstring. Read once at import; -3.0 ~= requiring roughly top-20-ish mass.
SGLANG_ORACLE_DRAFT_LOGPROB_THRESHOLD = float(
    os.environ.get("SGLANG_ORACLE_DRAFT_LOGPROB_THRESHOLD", "-3.0")
)

# Oracle-mode fixed commit length: > 0 replaces the draft-confidence gate
# with an unconditional N-forced-tokens-per-tick commit (capped by the
# block window and remaining forced sequence -- see
# compute_oracle_commit_fixed_len). 0 (default) keeps the gated behavior.
# Set to the deployment's historically measured accept length (~3-4) so
# oracle benchmarks exercise realistic accept-length dynamics instead of
# the gate's near-permanent floor of 1 on foreign-model traces.
SGLANG_ORACLE_FIXED_COMMIT_LEN = int(
    os.environ.get("SGLANG_ORACLE_FIXED_COMMIT_LEN", "0")
)

