def _ccd_debug_dump_tick(
    tag: str,
    out_tokens: torch.Tensor,
    commit_lens: torch.Tensor,
    target_predict: Optional[torch.Tensor] = None,
) -> None:
    if not _CCD_DEBUG_DUMP:
        return
    if torch.cuda.is_current_stream_capturing():
        return
    import json

    idx = _ccd_debug_tick_counter[0]
    _ccd_debug_tick_counter[0] = idx + 1
    record = {
        "tick": idx,
        "tag": tag,
        "out_tokens": out_tokens.reshape(-1).to("cpu").tolist(),
        "commit_lens": commit_lens.reshape(-1).to("cpu").tolist(),
        "target_predict": (
            target_predict.reshape(-1).to("cpu").tolist()
            if target_predict is not None
            else None
        ),
    }
    with open(_CCD_DEBUG_DUMP_PATH, "a") as f:
        f.write(json.dumps(record) + "\n")

