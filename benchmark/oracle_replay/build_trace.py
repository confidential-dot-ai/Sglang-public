"""Convert a real agent-trajectory dataset into oracle-mode replay JSONL.

Source dataset: Wejh/ninja-agent-traces on Hugging Face (multi-turn SWE-agent
trajectories generated by the open-weight Qwen/Qwen3.6-27B-FP8, with reasoning
kept inline in each turn's content up to a literal "</think>" marker -- unlike
most public agent-trace datasets, nothing here is stripped).

For each turn, the dataset's "payloads" table stores the exact request body
sent to the model (system/user/assistant/tool-output history) and the exact
response body (the model's real completion, reasoning included). This script
reassembles that per rollout, tokenizes each turn's real completion with the
target model's own tokenizer -- appending the target's own EOS token when
that turn's real generation actually ended on one (see tokenize_completion())
-- and emits one JSONL line per turn:

    {"messages": [...history up to this turn...],
     "sampling_params": {"forced_token_ids": [...], "max_new_tokens": N}}

Feed the lines for one rollout to a live server IN ORDER (see replay.py) so
each turn's forced completion becomes real prefix-cache content for the next
turn, the same way it would in genuine multi-turn serving.

Payload rows arrive chunked (chunk_index/chunk_count) because request/response
bodies can exceed a single row; reassembly is a plain ordered concatenation.
"""

from __future__ import annotations

import argparse
import glob
import json
from pathlib import Path

import pandas as pd
from transformers import AutoTokenizer


def load_payloads(parquet_glob: str) -> pd.DataFrame:
    paths = sorted(glob.glob(parquet_glob))
    if not paths:
        raise FileNotFoundError(f"no parquet files matched {parquet_glob!r}")
    return pd.concat((pd.read_parquet(p) for p in paths), ignore_index=True)


def reassemble(df: pd.DataFrame, direction: str, event_index: int) -> str:
    rows = df[(df["direction"] == direction) & (df["event_index"] == event_index)]
    rows = rows.sort_values("chunk_index")
    return "".join(rows["content"].tolist())


def strip_reasoning(content: str) -> str:
    """Drop everything up to and including the last "</think>" marker.

    This source dataset's own capture harness feeds each turn's full raw
    completion -- reasoning included -- back as history for later turns
    (confirmed on real data: every historical assistant message still
    contains "</think>"). That's not how reasoning-model serving actually
    behaves: providers strip prior reasoning before it re-enters context, so
    replaying it verbatim would understate real prefix-cache growth and
    overstate context length. Only strip on the way into *history*; the
    completion being forced for the current turn keeps its full reasoning.
    """
    if "</think>" not in content:
        return content
    return content.rsplit("</think>", 1)[1].lstrip("\n")


def extract_turns(df: pd.DataFrame, rollout_id: str) -> list[dict]:
    """Return one entry per turn: {"messages": [...], "completion": "...",
    "finish_reason": "..."}.

    ``messages`` is the exact request context for that turn (already in
    standard OpenAI role/content form); ``completion`` is the model's real
    response text for that turn, to be tokenized and forced; ``finish_reason``
    (``"stop"``, ``"length"``, ...) says whether that completion actually
    ended on a real EOS or was cut off -- see tokenize_completion().
    """
    sub = df[df["rollout_id"] == rollout_id]
    event_indices = sorted(
        i
        for i in sub.loc[sub["direction"] == "response", "event_index"].unique()
        if i >= 0
    )
    turns = []
    for event_index in event_indices:
        request_raw = reassemble(sub, "request", event_index)
        response_raw = reassemble(sub, "response", event_index)
        if not request_raw or not response_raw:
            continue
        request = json.loads(request_raw)
        response = json.loads(response_raw)
        choice = response.get("choices", [{}])[0]
        completion = choice.get("message", {}).get("content")
        if not completion:
            continue
        messages = [
            (
                {**m, "content": strip_reasoning(m["content"])}
                if m["role"] == "assistant"
                else m
            )
            for m in request["messages"]
        ]
        turns.append(
            {
                "messages": messages,
                "completion": completion,
                "finish_reason": choice.get("finish_reason"),
            }
        )
    return turns


def tokenize_completion(tokenizer, completion: str, finish_reason: str) -> list[int]:
    """Tokenize a turn's completion, appending the target tokenizer's own
    EOS token when (and only when) this turn's real generation actually
    ended on one (``finish_reason == "stop"``).

    Without this, a forced sequence just runs out mid-stream instead of
    ending the way a real generation would -- CCD's/eager's on-device finish
    detection matches committed tokens against the model's actual EOS id
    (see cc_conditional_decode.py's decode_finish_update), so a replayed
    turn without it never registers a natural EOS finish, and the row falls
    through to real (unforced, off-trace) generation for the remaining
    max_new_tokens slack instead of cleanly stopping at the turn boundary.
    Measured on this dataset: ~99.75% of turns are "stop" (2 shards, 200
    sampled rollouts); the ~0.25% "length" turns were genuinely cut off by
    the original call's max_tokens, so appending an EOS there would
    misrepresent a truncation as a natural finish.
    """
    token_ids = tokenizer.encode(completion)
    if finish_reason == "stop" and tokenizer.eos_token_id is not None:
        token_ids = token_ids + [tokenizer.eos_token_id]
    return token_ids


def build_rollout_jsonl(
    df: pd.DataFrame, rollout_id: str, tokenizer, max_new_tokens_slack: int = 8
) -> list[dict]:
    """One line per turn, ready for a chat-completions request with oracle
    mode's forced_token_ids set. max_new_tokens_slack pads past the forced
    length so SamplingParams.verify() (forced length <= max_new_tokens) has
    room, since stop-token handling can differ by tokenizer."""
    lines = []
    for turn in extract_turns(df, rollout_id):
        forced_token_ids = tokenize_completion(
            tokenizer, turn["completion"], turn["finish_reason"]
        )
        if not forced_token_ids:
            continue
        lines.append(
            {
                "messages": turn["messages"],
                "sampling_params": {
                    "forced_token_ids": forced_token_ids,
                    "max_new_tokens": len(forced_token_ids) + max_new_tokens_slack,
                },
            }
        )
    return lines


def build_combined_conversation(
    df: pd.DataFrame, rollout_id: str, tokenizer, max_new_tokens_slack: int = 8
) -> list[dict] | None:
    """One rollout as a list of per-round *deltas*, for
    ``sglang.benchmark.datasets.oracle_trace.OracleTraceDataset`` /
    ``python -m sglang.benchmark.serving --dataset-name oracle-trace``.

    Unlike ``build_rollout_jsonl`` (full context per line, for replay.py's
    direct chat-completions calls), each round here holds only the messages
    new since the previous round -- bench_serving's multi-turn wrapper fills
    in the assistant slot itself from the server's own (forced) reply, then
    appends this round's delta. Round 0's delta is the full initial context
    (system + task); round i>0's delta is whatever comes after the single
    assistant slot at the end of round i-1's full context -- by construction
    that's exactly the new tool-result message(s) for this round.
    """
    turns = extract_turns(df, rollout_id)
    rounds = []
    prev_len = 0
    for turn in turns:
        forced_token_ids = tokenize_completion(
            tokenizer, turn["completion"], turn["finish_reason"]
        )
        if not forced_token_ids:
            continue
        delta = (
            turn["messages"][prev_len:]
            if prev_len == 0
            else turn["messages"][prev_len + 1 :]
        )
        prev_len = len(turn["messages"])
        rounds.append(
            {
                "messages": delta,
                "forced_token_ids": forced_token_ids,
                "max_new_tokens": len(forced_token_ids) + max_new_tokens_slack,
            }
        )
    return rounds or None


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--payloads-parquet",
        required=True,
        help="Glob for Wejh/ninja-agent-traces 'payloads' config parquet shard(s)",
    )
    ap.add_argument(
        "--tokenizer",
        required=True,
        help="HF repo id or local path of the tokenizer to encode forced completions with "
        "(should match the model you're replaying against, e.g. MiniMaxAI/MiniMax-M3)",
    )
    ap.add_argument(
        "--rollout-id", action="append", help="Replay only these rollout_id(s)"
    )
    ap.add_argument(
        "--num-rollouts",
        type=int,
        default=None,
        help="If --rollout-id is not given, sample this many rollouts from the shard(s)",
    )
    ap.add_argument(
        "--output-dir", help="Per-rollout JSONL for replay.py (one file per rollout)"
    )
    ap.add_argument(
        "--combined-output",
        help="Single JSON file for `python -m sglang.benchmark.serving "
        "--dataset-name oracle-trace --dataset-path <this file>`",
    )
    args = ap.parse_args()
    if not args.output_dir and not args.combined_output:
        ap.error("at least one of --output-dir, --combined-output is required")

    df = load_payloads(args.payloads_parquet)
    tokenizer = AutoTokenizer.from_pretrained(args.tokenizer, trust_remote_code=True)

    if args.rollout_id:
        rollout_ids = args.rollout_id
    else:
        all_ids = df.loc[df["direction"] == "response", "rollout_id"].unique().tolist()
        rollout_ids = all_ids[: args.num_rollouts] if args.num_rollouts else all_ids

    if args.output_dir:
        out_dir = Path(args.output_dir)
        out_dir.mkdir(parents=True, exist_ok=True)
        for rollout_id in rollout_ids:
            lines = build_rollout_jsonl(df, rollout_id, tokenizer)
            if not lines:
                continue
            out_path = out_dir / f"{rollout_id}.jsonl"
            with out_path.open("w") as f:
                for line in lines:
                    f.write(json.dumps(line) + "\n")
            total_forced = sum(
                len(l["sampling_params"]["forced_token_ids"]) for l in lines
            )
            print(
                f"{rollout_id}: {len(lines)} turns, {total_forced} forced tokens -> {out_path}"
            )

    if args.combined_output:
        conversations = []
        for rollout_id in rollout_ids:
            rounds = build_combined_conversation(df, rollout_id, tokenizer)
            if rounds:
                conversations.append(rounds)
        combined = {
            "metadata": {
                "source": "Wejh/ninja-agent-traces",
                "tokenizer": args.tokenizer,
            },
            "conversations": conversations,
        }
        with open(args.combined_output, "w") as f:
            json.dump(combined, f)
        total_forced = sum(
            len(r["forced_token_ids"]) for conv in conversations for r in conv
        )
        print(
            f"{len(conversations)} conversations, {total_forced} forced tokens "
            f"-> {args.combined_output}"
        )


if __name__ == "__main__":
    main()
