def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


def atomic_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=path.parent, delete=False) as handle:
        json.dump(payload, handle, indent=2, sort_keys=True)
        handle.write("\n")
        temporary = Path(handle.name)
    temporary.replace(path)


def jsonable(value: Any) -> Any:
    if isinstance(value, Path):
        return str(value)
    if isinstance(value, tuple):
        return [jsonable(item) for item in value]
    if isinstance(value, list):
        return [jsonable(item) for item in value]
    if isinstance(value, dict):
        return {str(key): jsonable(item) for key, item in value.items()}
    return value


def render_profile_env(profile: dict[str, str], header: Iterable[str] = ()) -> str:
    unknown = set(profile) - PROFILE_KEYS
    if unknown:
        raise ValueError(f"profile contains non-allowlisted keys: {sorted(unknown)}")
    lines = ["# Generated by benchmark/deepseek_v4_b300/tune.py; do not hand-edit."]
    lines.extend(f"# {line}" for line in header)
    lines.extend(
        f"export {key}={shlex.quote(str(profile[key]))}" for key in sorted(profile)
    )
    return "\n".join(lines) + "\n"


def weighted_latency_ratio(
    candidate: dict[str, float], baseline: dict[str, float], weights: dict[str, float]
) -> float:
    if set(candidate) != set(baseline) or not candidate:
        raise ValueError("candidate and baseline must cover identical shapes")
    numerator = 0.0
    denominator = 0.0
    for shape in sorted(candidate):
        weight = float(weights.get(shape, 1.0))
        candidate_value = float(candidate[shape])
        baseline_value = float(baseline[shape])
        if candidate_value <= 0 or baseline_value <= 0 or weight < 0:
            raise ValueError("latencies must be positive and weights non-negative")
        numerator += weight * math.log(candidate_value / baseline_value)
        denominator += weight
    if denominator <= 0:
        raise ValueError("collective weights must have positive total weight")
    return math.exp(numerator / denominator)


def collective_payload_is_correct(payload: dict[str, Any], require_cc: bool) -> bool:
    cc = payload.get("hardware_cc_state", {})
    if require_cc and not (
        cc.get("query_ok") is True
        and cc.get("enabled") is True
        and int(cc.get("devtools_mode", 1)) == 0
    ):
        return False
    if float(payload.get("correctness_max_abs_error", math.inf)) != 0.0:
        return False
    rows = payload.get("results", [])
    if not rows:
        return False
    for row in rows:
        results = row.get("pynccl", [])
        if not results:
            return False
        result = results[0]
        if (
            float(result.get("eager_max_abs_error", math.inf)) != 0.0
            or float(result.get("graph_max_abs_error", math.inf)) != 0.0
            or result.get("graph_replay_ms") is None
        ):
            return False
    return True


def collective_latencies(payload: dict[str, Any]) -> dict[str, float]:
    return {
        f"{float(row['message_mib']):g}MiB": float(
            row["pynccl"][0]["graph_replay_ms"]["max_rank_ms"]
        )
        for row in payload["results"]
    }


def collective_payload_matches_definition(
    payload: dict[str, Any], *, algo: str, proto: str, nvls: bool
) -> bool:
    return (
        str(payload.get("nccl_algo", "")).lower() == f"allreduce:{algo}".lower()
        and str(payload.get("nccl_proto", "")).lower()
        == f"allreduce:{proto}".lower()
        and payload.get("nccl_nvls_enable") == ("1" if nvls else "0")
        and payload.get("nccl_buffsize") == str(4 * 1024 * 1024)
    )


def select_collective(
    payloads: dict[str, dict[str, Any]],
    *,
    baseline_name: str,
    weights: dict[str, float],
    require_cc: bool,
    minimum_speedup: float = 1.02,
    maximum_shape_regression: float = 1.10,
) -> dict[str, Any]:
    valid = {
        name: collective_latencies(payload)
        for name, payload in payloads.items()
        if collective_payload_is_correct(payload, require_cc)
    }
    if baseline_name not in valid:
        raise ValueError("the Ring/LL baseline did not pass correctness and CC gates")
    baseline = valid[baseline_name]
    if set(baseline) != set(weights):
        raise ValueError("collective results do not match the declared shape profile")
    ratios = {
        name: weighted_latency_ratio(values, baseline, weights)
        for name, values in valid.items()
    }
    worst = {
        name: max(values[shape] / baseline[shape] for shape in baseline)
        for name, values in valid.items()
    }
    safe = [name for name in valid if worst[name] <= maximum_shape_regression]
    winner = min(safe, key=ratios.get) if safe else baseline_name
    selected = winner if ratios[winner] <= 1.0 / minimum_speedup else baseline_name
    return {
        "selected": selected,
        "performance_winner": min(ratios, key=ratios.get),
        "ratios_vs_baseline": ratios,
        "worst_shape_ratios_vs_baseline": worst,
        "valid_candidates": sorted(valid),
        "invalid_candidates": sorted(set(payloads) - set(valid)),
        "minimum_speedup": minimum_speedup,
        "maximum_shape_regression": maximum_shape_regression,
    }


def _latency_value(bundle: dict[str, Any], key: str) -> float | None:
    value = bundle["replay"].get("latency", {}).get("fixed_window", {}).get(key)
    return None if value is None else float(value)


def select_variant(
    bundles: dict[str, dict[str, Any]],
    *,
    baseline_name: str,
    minimum_speedup: float = 1.02,
    minimum_drain_ratio: float = 0.98,
    maximum_latency_regression: float = 1.05,
) -> dict[str, Any]:
    valid = {
        name: bundle for name, bundle in bundles.items() if not validate_bundle(bundle)
    }
    if baseline_name not in valid:
        raise ValueError("baseline variant did not pass replay and correctness gates")
    baseline = valid[baseline_name]
    baseline_fixed = float(
        baseline["replay"]["metrics"]["fixed_window"]["served_tpm_per_gpu"]
    )
    baseline_drain = float(
        baseline["replay"]["metrics"]["drain_inclusive"]["served_tpm_per_gpu"]
    )
    rows: dict[str, dict[str, Any]] = {}
    for name, bundle in valid.items():
        fixed = float(bundle["replay"]["metrics"]["fixed_window"]["served_tpm_per_gpu"])
        drain = float(bundle["replay"]["metrics"]["drain_inclusive"]["served_tpm_per_gpu"])
        latency_ratios: dict[str, float] = {}
        for key in ("ttft_p50", "token_itl_ms_p50"):
            control = _latency_value(baseline, key)
            candidate = _latency_value(bundle, key)
            if control is not None and candidate is not None and control > 0:
                latency_ratios[key] = candidate / control
        rows[name] = {
            "fixed_ratio": fixed / baseline_fixed,
            "drain_ratio": drain / baseline_drain,
            "latency_ratios": latency_ratios,
            "safe": drain / baseline_drain >= minimum_drain_ratio
            and all(
                ratio <= maximum_latency_regression
                for ratio in latency_ratios.values()
            ),
        }
    safe = [name for name, row in rows.items() if row["safe"]]
    winner = max(safe, key=lambda name: rows[name]["fixed_ratio"])
    selected = (
        winner
        if rows[winner]["fixed_ratio"] >= minimum_speedup
        else baseline_name
    )
    return {
        "selected": selected,
        "performance_winner": max(rows, key=lambda name: rows[name]["fixed_ratio"]),
        "valid_candidates": sorted(valid),
        "invalid_candidates": sorted(set(bundles) - set(valid)),
        "results": rows,
        "minimum_speedup": minimum_speedup,
        "minimum_drain_ratio": minimum_drain_ratio,
        "maximum_latency_regression": maximum_latency_regression,
    }


def parse_named_path(value: str) -> tuple[str, Path]:
    if "=" not in value:
        raise argparse.ArgumentTypeError("candidate artifacts require NAME=PATH")
    name, path = value.split("=", 1)
    if not name or not path:
        raise argparse.ArgumentTypeError("candidate artifacts require NAME=PATH")
    return name, Path(path)


def load_shape_profile(path: Path) -> dict[str, float]:
    payload = json.loads(path.read_text())
    values = payload.get("collective_weights")
    if not isinstance(values, dict) or not values:
        raise ValueError("shape profile requires a non-empty collective_weights object")
    weights = {str(key): float(value) for key, value in values.items()}
    if any(value < 0 for value in weights.values()) or sum(weights.values()) <= 0:
        raise ValueError("collective weights must be non-negative with positive sum")
    return weights


@dataclass
class RunRecord:
    name: str
    command: list[str]
    environment: dict[str, str]
    status: str
    returncode: int | None
    log: str


class Runner:
    def __init__(self, output_dir: Path, repo_root: Path, dry_run: bool) -> None:
        self.output_dir = output_dir
        self.repo_root = repo_root
        self.dry_run = dry_run
        self.records: list[dict[str, Any]] = []

    def run(self, name: str, command: list[str], environment: dict[str, str]) -> RunRecord:
        log_path = self.output_dir / "logs" / f"{name}.log"
        log_path.parent.mkdir(parents=True, exist_ok=True)
        if self.dry_run:
            record = RunRecord(name, command, environment, "planned", None, str(log_path))
        else:
            merged = os.environ.copy()
            merged.update(environment)
            with log_path.open("w") as log:
                log.write(f"command={shlex.join(command)}\n")
                log.write(f"environment={json.dumps(environment, sort_keys=True)}\n")
                process = subprocess.run(
                    command,
                    cwd=self.repo_root,
                    env=merged,
                    text=True,
                    stdout=log,
                    stderr=subprocess.STDOUT,
                    check=False,
                )
            record = RunRecord(
                name,
                command,
                environment,
                "passed" if process.returncode == 0 else "failed",
                process.returncode,
                str(log_path),
            )
        self.records.append(record.__dict__)
        return record


class Tuner:
    def __init__(self, args: argparse.Namespace) -> None:
        self.args = args
        self.repo = args.repo_root.resolve()
        self.output = args.output_dir.resolve()
        self.output.mkdir(parents=True, exist_ok=True)
        self.profile = dict(DEFAULT_PROFILE)
        self.runner = Runner(self.output, self.repo, args.dry_run)
        self.report: dict[str, Any] = {
            "schema_version": 1,
            "created_utc": utc_now(),
            "arguments": jsonable(vars(args)),
            "profile": self.profile,
            "suites": {},
        }

    def preflight(self) -> None:
        if self.args.dry_run:
            self.report["hardware"] = {"status": "not inspected in dry-run"}
            return
        self.report["hardware"] = inspect(
            repo_root=self.repo,
            selected_gpu_indices=self.args.gpus,
            expected_gpu_count=8,
            require_cc=self.args.require_cc,
            require_idle=not self.args.allow_busy_gpus,
            allow_non_b300=self.args.allow_non_b300,
            attestation_evidence=self.args.attestation_evidence,
            require_attestation=self.args.require_attestation,
            python_executable=self.args.python,
        )

    def collectives(self) -> dict[str, Any]:
        if self.args.shape_profile is not None:
            weights = load_shape_profile(self.args.shape_profile)
        elif self.args.dry_run:
            weights = dict(SEED_COLLECTIVE_WEIGHTS)
        else:
            raise RuntimeError(
                "a measured --shape-profile is required for non-dry-run collective tuning"
            )
        sizes = [shape.removesuffix("MiB") for shape in weights]
        definitions = {
            "ring-ll": ("Ring", "LL", False),
            "ring-simple": ("Ring", "Simple", False),
            "tree-simple": ("Tree", "Simple", False),
            "nvls-simple": ("NVLS", "Simple", True),
        }
        if not self.args.quick:
            definitions.update(
                {
                    "ring-ll128": ("Ring", "LL128", False),
                    "tree-ll128": ("Tree", "LL128", False),
                    "nvlstree-simple": ("NVLSTree", "Simple", True),
                }
            )
        payloads: dict[str, dict[str, Any]] = {}
        for name, (algo, proto, nvls) in definitions.items():
            result_path = self.output / "results" / f"collective-{name}.json"
            result_path.parent.mkdir(parents=True, exist_ok=True)
            command = [
                self.args.python,
                "-m",
                "torch.distributed.run",
                "--standalone",
                "--nproc-per-node=4",
                str(self.repo / "scripts/bench_nccl_allreduce.py"),
                "--message-mib",
                *sizes,
                "--warmup",
                "8" if self.args.quick else "20",
                "--iterations",
                "20" if self.args.quick else "100",
                "--cuda-graph",
                "--output-json",
                str(result_path),
            ]
            if self.args.require_cc:
                command.append("--require-cc-nvls" if nvls else "--require-cc")
            environment = {
                "CUDA_VISIBLE_DEVICES": ",".join(map(str, self.args.gpus)),
                "NCCL_ALGO": f"allreduce:{algo}",
                "NCCL_PROTO": f"allreduce:{proto}",
                "NCCL_NVLS_ENABLE": "1" if nvls else "0",
                "NCCL_BUFFSIZE": str(4 * 1024 * 1024),
                "OMP_NUM_THREADS": "1",
                "PYTHONPATH": str(self.repo / "python"),
            }
            run = self.runner.run(f"collective-{name}", command, environment)
            if run.status == "passed" and result_path.exists():
                payload = json.loads(result_path.read_text())
                if not collective_payload_matches_definition(
                    payload, algo=algo, proto=proto, nvls=nvls
                ):
                    raise RuntimeError(
                        f"collective result does not match requested environment: {name}"
                    )
                payloads[name] = payload

        if self.args.dry_run:
            return {
                "status": "planned",
                "shape_weights": weights,
                "candidates": definitions,
            }
        selection = select_collective(
            payloads,
            baseline_name="ring-ll",
            weights=weights,
            require_cc=self.args.require_cc,
        )
        selected = selection["selected"]
        algo, proto, nvls = definitions[selected]
        self.profile.update(
            NCCL_ALGO=f"allreduce:{algo}",
            NCCL_PROTO=f"allreduce:{proto}",
            NCCL_NVLS_ENABLE="1" if nvls else "0",
            NCCL_BUFFSIZE=str(4 * 1024 * 1024),
            DSV4_NCCL_AUTO_CTAS="1",
        )
        return {
            "status": "passed",
            "shape_weights": weights,
            "selection": selection,
            "payloads": payloads,
        }

    def variants(self) -> dict[str, Any]:
        paths = dict(self.args.variant_result)
        if not paths:
            return {
                "status": "planned",
                "required_controls": [
                    "fp32-default",
                    "bf16-default",
                    "fp32-fp4-indexer",
                    "bf16-fp4-indexer",
                ],
                "note": "bundle matched replay and probe artifacts with bundle_candidate.py",
            }
        bundles = {name: json.loads(path.read_text()) for name, path in paths.items()}
        selection = select_variant(
            bundles,
            baseline_name=self.args.baseline_variant,
            minimum_speedup=self.args.minimum_variant_speedup,
            minimum_drain_ratio=self.args.minimum_drain_ratio,
            maximum_latency_regression=self.args.maximum_latency_regression,
        )
        selected_bundle = bundles[selection["selected"]]
        unknown = set(selected_bundle["configuration"]) - PROFILE_KEYS
        if unknown:
            raise ValueError(f"selected variant contains unknown profile keys: {sorted(unknown)}")
        self.profile.update(
            {key: str(value) for key, value in selected_bundle["configuration"].items()}
        )
        return {"status": "passed", "selection": selection}

    def save(self) -> None:
        self.report["commands"] = self.runner.records
        atomic_json(self.output / "profile.json", self.report)
        source_revision = (
            self.report.get("hardware", {})
            .get("repository", {})
            .get("git_sha", "dry-run")
        )
        (self.output / "profile.env").write_text(
            render_profile_env(
                self.profile,
                header=(
                    f"created: {self.report['created_utc']}",
                    f"source revision: {source_revision}",
                ),
            )
        )

    def run(self) -> int:
        self.preflight()
        failed = False
        for suite_name in self.args.suites:
            try:
                self.report["suites"][suite_name] = getattr(self, suite_name)()
            except Exception as exc:
                failed = True
                self.report["suites"][suite_name] = {
                    "status": "failed",
                    "error": repr(exc),
                }
                self.save()
                if not self.args.continue_on_error:
                    raise
        self.save()
        return 1 if failed else 0


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=REPO_ROOT)
    parser.add_argument("--python", default=sys.executable)
    parser.add_argument("--gpus", type=parse_gpu_indices, default=[0, 1, 2, 3])
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument(
        "--suites",
        nargs="+",
        choices=("collectives", "variants"),
        default=["collectives", "variants"],
    )
    parser.add_argument("--shape-profile", type=Path)
    parser.add_argument("--variant-result", type=parse_named_path, action="append", default=[])
    parser.add_argument("--baseline-variant", default="fp32-default")
    parser.add_argument("--minimum-variant-speedup", type=float, default=1.02)
    parser.add_argument("--minimum-drain-ratio", type=float, default=0.98)
    parser.add_argument("--maximum-latency-regression", type=float, default=1.05)
    parser.add_argument("--attestation-evidence", type=Path)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--quick", action="store_true")
    parser.add_argument("--continue-on-error", action="store_true")
    parser.add_argument("--allow-non-b300", action="store_true")
    parser.add_argument("--allow-busy-gpus", action="store_true")
    parser.add_argument("--no-require-cc", dest="require_cc", action="store_false")
    parser.add_argument(
        "--no-require-attestation",
        dest="require_attestation",
        action="store_false",
    )
    parser.set_defaults(require_cc=True, require_attestation=True)
    args = parser.parse_args()
    if len(args.gpus) != 4:
        parser.error("--gpus must select exactly four GPUs for one TP4 island")
    if not args.dry_run and args.require_attestation and args.attestation_evidence is None:
        parser.error("--attestation-evidence is required outside dry-run")
    return args


def main() -> int:
    return Tuner(parse_args()).run()


if __name__ == "__main__":
    raise SystemExit(main())
